#!/usr/bin/env bash
# Build the LaTeX edition of the French Embassy project report.
#
#   bash reports/french_embassy/latex/build.sh            # build (from any directory)
#   bash reports/french_embassy/latex/build.sh --clean    # delete build/ and generated/ first
#
# Output: reports/french_embassy/outputs/final_project_report_latex.pdf
#
# The authoritative source of the text is reports/french_embassy/report.md. This script
# converts it with pandoc + the Lua filters in filters/, typesets the result tables from
# the CSV files in table_manifest.csv, and compiles main.tex with LuaLaTeX and biber
# (through latexmk). It runs no model, analysis or ranking: it only reads saved outputs.
#
# The build FAILS, and no PDF is copied to outputs/, if: a tool or LaTeX package is
# missing; a figure, table or CSV column is missing; a figure's number or caption differs
# from figure_manifest.csv; a textual reference (Figure N, Table X, section N) has no
# target; a citation or cross-reference is undefined; a character is missing from the
# fonts; a float is too large for the page; or a label's final number differs from the
# number used in report.md.
#
# Requirements: pandoc >= 3.1, LuaLaTeX, latexmk, biber, and the fonts Linux Libertine O,
# Linux Biolinum O and DejaVu (all present on the investigator's machine, 2026-10-22).

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "${HERE}/../../.." && pwd)"
GEN="${HERE}/generated"
BUILD="${HERE}/build"
OUT_PDF="${ROOT}/reports/french_embassy/outputs/final_project_report_latex.pdf"

die() { echo "ERROR: $*" >&2; exit 1; }
note() { echo "NOTE: $*" >&2; }

if [ "${1:-}" = "--clean" ]; then
  rm -rf "${BUILD}" "${GEN}"
elif [ $# -gt 0 ]; then
  die "usage: build.sh [--clean]"
fi

# --- tools --------------------------------------------------------------------------------
for tool in pandoc lualatex latexmk biber; do
  command -v "${tool}" >/dev/null 2>&1 || die "${tool} is not installed; it is required."
done
PANDOC_VERSION="$(pandoc --version | head -n 1 | cut -d' ' -f2)"
major="${PANDOC_VERSION%%.*}"
minor="${PANDOC_VERSION#*.}"
minor="${minor%%.*}"
if [ "${major}" -lt 3 ] || { [ "${major}" -eq 3 ] && [ "${minor}" -lt 1 ]; }; then
  die "pandoc >= 3.1 is required (found ${PANDOC_VERSION})."
fi

# --- inputs (repository-relative, so generated files contain no machine paths) -----------
cd "${ROOT}"
SRC=reports/french_embassy/report.md
BIB=reports/french_embassy/references.bib
FIGMAN=reports/french_embassy/figure_manifest.csv
TABMAN=reports/french_embassy/table_manifest.csv
CAPTIONS=results/tables/primary_v1/publication_v1/captions.md
for f in "${SRC}" "${BIB}" "${FIGMAN}" "${TABMAN}" "${CAPTIONS}"; do
  [ -f "${f}" ] || die "missing input ${f}"
done
mkdir -p "${GEN}" "${BUILD}" "$(dirname "${OUT_PDF}")"

# --- 1. report.md -> LaTeX fragments ------------------------------------------------------
echo "[1/4] Converting report.md (pandoc ${PANDOC_VERSION})"
for part in metadata summary main appendices; do
  pandoc "${SRC}" --from=markdown --to=latex --top-level-division=chapter --biblatex \
    --wrap=preserve --lua-filter="${HERE}/filters/report.lua" \
    -M report-part="${part}" -M figure-manifest="${FIGMAN}" -M table-manifest="${TABMAN}" \
    -M labels-file="${GEN}/expected_labels_report.txt" \
    -o "${GEN}/${part}.tex"
done

# --- 2. result CSVs -> LaTeX tables -------------------------------------------------------
echo "[2/4] Typesetting result tables from table_manifest.csv"
pandoc /dev/null --from=markdown --to=latex --lua-filter="${HERE}/filters/datatables.lua" \
  -M table-manifest="${TABMAN}" -M figure-manifest="${FIGMAN}" -M captions-file="${CAPTIONS}" \
  -M report-source="${SRC}" -M bib-file="${BIB}" \
  -M labels-file="${GEN}/expected_labels_tables.txt" -M sources-file="${GEN}/sources.txt" \
  -o "${GEN}/data_tables.tex"

# --- 3. provenance: checksums, commit, dates ----------------------------------------------
echo "[3/4] Recording provenance"
sha() { sha256sum "$1" | cut -d' ' -f1; }
# A fixed timestamp makes repeated builds of unchanged inputs identical. By default it is
# the modification time of report.md; set SOURCE_DATE_EPOCH to override.
SOURCE_DATE_EPOCH="${SOURCE_DATE_EPOCH:-$(stat -c %Y "${SRC}")}"
FORCE_SOURCE_DATE=1
export SOURCE_DATE_EPOCH FORCE_SOURCE_DATE
build_date="$(date -u -d "@${SOURCE_DATE_EPOCH}" +%Y-%m-%d)"
commit="$(git rev-parse --short=12 HEAD 2>/dev/null || echo unavailable)"
if [ -n "$(git status --porcelain 2>/dev/null | head -n 1)" ]; then
  tree_state="working tree with uncommitted or untracked changes"
else
  tree_state="clean working tree"
fi
n_figures="$(($(wc -l < "${FIGMAN}") - 1))"
n_tables="$(($(wc -l < "${TABMAN}") - 1))"
{
  printf '%s\n' '% GENERATED by latex/build.sh. Do not edit.'
  printf '\\newcommand{\\BuildSourceSHA}{\\reportpath{%s}}\n' "$(sha "${SRC}")"
  printf '\\newcommand{\\BuildBibSHA}{\\reportpath{%s}}\n' "$(sha "${BIB}")"
  printf '\\newcommand{\\BuildCommit}{\\reportpath{%s}}\n' "${commit}"
  printf '\\newcommand{\\BuildTreeState}{%s}\n' "${tree_state}"
  printf '\\newcommand{\\BuildDate}{%s}\n' "${build_date}"
  printf '\\newcommand{\\BuildPandocVersion}{%s}\n' "${PANDOC_VERSION}"
  printf '\\newcommand{\\BuildFigureCount}{%s}\n' "${n_figures}"
  printf '\\newcommand{\\BuildTableCount}{%s}\n' "${n_tables}"
} > "${GEN}/buildinfo.tex"

{
  printf '%s\n' '% GENERATED by latex/build.sh from generated/sources.txt. Do not edit.'
  printf '%s\n' '\begin{ReportDataTable}{\footnotesize}'
  printf '%s\n' '\begin{longtable}{@{}>{\raggedright\arraybackslash}p{\dimexpr 0.50\linewidth-2\tabcolsep\relax}>{\raggedright\arraybackslash}p{\dimexpr 0.50\linewidth-2\tabcolsep\relax}@{}}'
  printf '%s\n' '\caption{Input files of this document and their SHA-256 checksums}\label{tab-provenance}\\'
  printf '%s\n' '\toprule \reporttablehead{File (repository path)} & \reporttablehead{SHA-256} \\ \midrule \endfirsthead'
  printf '%s\n' '\toprule \reporttablehead{File (repository path)} & \reporttablehead{SHA-256} \\ \midrule \endhead'
  printf '%s\n' '\bottomrule \endlastfoot'
  while IFS= read -r path; do
    [ -n "${path}" ] || continue
    [ -f "${path}" ] || die "input listed in a manifest is missing: ${path}"
    printf '\\reportpath{%s} & \\reportpath{%s} \\\\\n' "${path}" "$(sha "${path}")"
  done < "${GEN}/sources.txt"
  printf '%s\n' '\end{longtable}'
  printf '%s\n' '\end{ReportDataTable}'
} > "${GEN}/sources.tex"

# --- 4. LaTeX -----------------------------------------------------------------------------
echo "[4/4] Compiling with LuaLaTeX and biber (latexmk)"
cd "${HERE}"
if ! latexmk -g main.tex > "${BUILD}/latexmk.out" 2>&1; then
  echo "LaTeX build FAILED. First errors from build/main.log:" >&2
  grep -nE '^!|:[0-9]+: ' "${BUILD}/main.log" 2>/dev/null | head -n 20 >&2 || true
  echo "--- last lines of latexmk output (build/latexmk.out) ---" >&2
  tail -n 25 "${BUILD}/latexmk.out" >&2
  exit 1
fi

LOG="${BUILD}/main.log"
BLG="${BUILD}/main.blg"
AUX="${BUILD}/main.aux"
problems=0
check() { # check <extended regex> <file> <description>
  if [ -f "$2" ] && grep -qE "$1" "$2"; then
    echo "FAIL: $3" >&2
    grep -E "$1" "$2" | head -n 8 | sed 's/^/      /' >&2
    problems=1
  fi
}
check 'Citation .* undefined' "${LOG}" "undefined citations"
check 'Reference .* undefined|There were undefined references' "${LOG}" \
  "undefined cross-references"
check 'multiply defined' "${LOG}" "multiply defined labels"
check 'Missing character' "${LOG}" "characters missing from every font"
check 'Float too large' "${LOG}" "a float is larger than the page (it would be clipped)"
check 'Label\(s\) may have changed' "${LOG}" "cross-references did not settle"
check '^ERROR|I didn.t find a database entry|Cannot find|not found' "${BLG}" \
  "bibliography (biber) errors"

# Every number that report.md uses for a figure, table, chapter or appendix must be the
# number LaTeX assigned.
while read -r label number; do
  [ -n "${label}" ] || continue
  if ! grep -qF "\\newlabel{${label}}{{${number}}{" "${AUX}"; then
    echo "FAIL: ${label} should be numbered ${number} in the PDF" >&2
    problems=1
  fi
done < <(cat "${GEN}/expected_labels_report.txt" "${GEN}/expected_labels_tables.txt")

if [ "${problems}" -ne 0 ]; then
  die "checks failed; the PDF was NOT copied to outputs/. Logs: ${BUILD}/main.log"
fi

# --- warnings that do not stop the build --------------------------------------------------
overfull="$(grep -cE 'Overfull \\hbox' "${LOG}" || true)"
wide="$(grep -E 'Overfull \\hbox \(([1-9][0-9]*\.[0-9]+)pt too wide' "${LOG}" || true)"
if [ -n "${wide}" ]; then
  note "${overfull} overfull line(s); those wider than 1pt:"
  printf '%s\n' "${wide}" | head -n 15 | sed 's/^/      /' >&2
fi
biber_warnings="$(grep -c 'WARN' "${BLG}" 2>/dev/null || true)"
[ "${biber_warnings:-0}" -eq 0 ] || note "biber reported ${biber_warnings} warning(s); see ${BLG}"
placeholders="$(grep -c 'TO BE COMPLETED' "${ROOT}/${SRC}" || true)"
[ "${placeholders:-0}" -eq 0 ] || note "report.md still has ${placeholders} line(s) marked [TO BE COMPLETED]."

cp "${BUILD}/main.pdf" "${OUT_PDF}"
pages=""
if command -v pdfinfo >/dev/null 2>&1; then
  pages="$(pdfinfo "${OUT_PDF}" | grep -E '^Pages:' | tr -s ' ' | cut -d' ' -f2)"
fi
echo "Done: ${OUT_PDF#"${ROOT}"/}${pages:+ (${pages} pages)}"
