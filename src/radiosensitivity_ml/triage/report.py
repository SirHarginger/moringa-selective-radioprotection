"""Generate triage tables for an evaluated and explained run (investigator-run).

Reads only saved, validated outputs: the run manifest, the evaluation tables and the
explainability tables of one run, plus QC metadata (no outcome beyond what evaluation
already wrote). Never fits, predicts or recomputes anything of the primary experiment.
Writes a write-once folder ``<output_dir>/<run_id>/`` with:
- ``pathway_candidates.csv``           gene-set triage;
- ``cell_line_validation_priorities.csv``  measured CLARIFi lines (replication /
  investigation); new DepMap lines are DEFERRED (see the manifest);
- ``discrepancy_review.csv``           held-out discrepancy and technical review;
- ``triage_manifest.json``             provenance, rules, gate status, deferred parts.
"""

