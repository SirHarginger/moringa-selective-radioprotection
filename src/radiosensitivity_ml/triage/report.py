@dataclass(frozen=True)
class TriageConfig:
    """Validated triage settings (configs/triage.yaml)."""

    raw: Mapping[str, object]
    experiment_config: Path
    tables_root: Path
    output_dir: Path
    external_evidence: Path | None
    pathway: tr.PathwayRules
    cell_lines: tr.CellLineRules

    @property
    def sha256(self) -> str:
        return config_sha256(self.raw)


def triage_from_mapping(data: Mapping[str, object]) -> TriageConfig:
    """Strict keys; every threshold must be given explicitly (no hidden defaults)."""
    if set(data) != TRIAGE_KEYS:
        raise tr.TriageError(f"triage config keys must be exactly {sorted(TRIAGE_KEYS)}")
    if data["schema_version"] != 1:
        raise tr.TriageError("schema_version must be 1")
    try:
        pathway = tr.PathwayRules(**data["pathway"])  # type: ignore[arg-type]
        cell_lines = tr.CellLineRules(**data["cell_lines"])  # type: ignore[arg-type]
    except TypeError as exc:
        raise tr.TriageError(f"invalid pathway / cell_lines settings: {exc}") from exc
    for name in ("strong", "moderate", "exploratory", "max_share_zero", "correlation_flag"):
        if not 0 < getattr(pathway, name) <= 1:
            raise tr.TriageError(f"pathway.{name} must be in (0, 1]")
    if not pathway.exploratory <= pathway.moderate <= pathway.strong:
        raise tr.TriageError("pathway thresholds must satisfy exploratory <= moderate <= strong")
    if pathway.min_null_draws < 1000:
        raise tr.TriageError("pathway.min_null_draws must be >= 1000 (protocol §15)")
    if not 0 < cell_lines.flag_percentile <= cell_lines.high_percentile < 1:
        raise tr.TriageError("cell_lines percentiles must satisfy 0 < flag <= high < 1")
    external = data["external_evidence"]
    return TriageConfig(
        raw=dict(data),
        experiment_config=Path(str(data["experiment_config"])),
        tables_root=Path(str(data["tables_root"])),
        output_dir=Path(str(data["output_dir"])),
        external_evidence=None if external is None else Path(str(external)),
        pathway=pathway,
        cell_lines=cell_lines,
    )


def load_triage(path: Path) -> TriageConfig:
    import yaml

    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(data, Mapping):
        raise tr.TriageError(f"{path} is not a YAML mapping")
    return triage_from_mapping(data)


def read_json(path: Path) -> dict[str, object]:
    if not path.is_file():
        raise tr.TriageError(f"{path} is missing; run the earlier pipeline steps first")
    return json.loads(path.read_text(encoding="utf-8"))


def verified_provenance(experiment: ExperimentConfig, tables_dir: Path) -> dict[str, object]:
    """Check that evaluation, explainability and the run manifest belong together."""
    record_path = tables_dir / "evaluation_record.json"
    record = read_json(record_path)
    if (
        record.get("config_sha256") != experiment.sha256
        or record.get("run_id") != experiment.run_id
    ):
        raise tr.TriageError(f"{record_path} belongs to another config or run_id")
    manifest_path = experiment.output_dir / experiment.run_id / "run_manifest.json"
    if not manifest_path.is_file():
        raise tr.TriageError(f"{manifest_path} is missing")
    if file_sha256(manifest_path) != record.get("run_manifest_sha256"):
        raise tr.TriageError("run_manifest.json changed after evaluation")
    stability_path = tables_dir / "explainability" / "stability.json"
    stability = read_json(stability_path)
    if stability.get("config_sha256") != experiment.sha256:
        raise tr.TriageError(f"{stability_path} belongs to another config")
    manifest = read_json(manifest_path)
    return {
        "run_id": experiment.run_id,
        "experiment_config_sha256": experiment.sha256,
        "evaluation_record_sha256": file_sha256(record_path),
        "run_manifest_sha256": file_sha256(manifest_path),
        "splits_sha256": manifest.get("splits_sha256"),
        "inputs_sha256": manifest.get("inputs_sha256"),
        "stability_json_sha256": file_sha256(stability_path),
    }


def cell_line_metadata(experiment: ExperimentConfig) -> pd.DataFrame:
    """QC metadata per eligible record (hash-verified; no outcome)."""
    qc_dir = Path(str(experiment.inputs["qc_dir"]))
    options = experiment.population_options
    population = at.load_population(
        qc_dir,
        dict(experiment.inputs["qc_sha256"]),  # type: ignore[arg-type]
        experiment.population,
        min_components=int(options.get("min_components_per_tissue", 10)),  # type: ignore[arg-type]
        stranded_ids=frozenset(options.get("stranded_ids", ())),  # type: ignore[arg-type]
    )
    table = population.table
    eligibility = pd.read_csv(qc_dir / "eligibility.csv", dtype=str)
    eligibility.index = eligibility["row_number"].astype(int)
    extra = eligibility.loc[table.index]
    stranded = set(options.get("stranded_ids", ()))  # type: ignore[arg-type]
    per_lineage = table.groupby("lineage")["component_id"].nunique()
    return pd.DataFrame(
        {
            "depmap_id": table["depmap_id"],
            "lineage": table["lineage"],
            "component_id": table["component_id"],
            "component_records": extra["component_records"].astype(int),
            "related_flag_sources": extra["component_flag_sources"].fillna(""),
            "stranded": table["depmap_id"].isin(stranded),
            "tissue_components": table["lineage"].map(per_lineage).astype(int),
            "pooled_stratum": table["stratum"] == at.STRATUM_POOLED,
        },
        index=table.index,
    )


def gate_status(comparisons: pd.DataFrame) -> tuple[bool, str]:
    """Primary comparison verdict (M2 vs M1, raw), copied from evaluation."""
    row = comparisons[
        (comparisons["model"] == "M2")
        & (comparisons["comparator"] == "M1")
        & (comparisons["scale"] == "raw")
    ]
    if len(row) != 1:
        raise tr.TriageError("comparisons.csv lacks exactly one primary M2 vs M1 raw row")
    verdict = str(row["verdict"].iloc[0])
    return verdict.startswith("gain shown"), verdict


def code_sha256() -> dict[str, str]:
    folder = Path(__file__).resolve().parent
    return {p.name: file_sha256(p) for p in sorted(folder.glob("*.py"))}


def generate_triage(config: TriageConfig, experiment: ExperimentConfig | None = None) -> Path:
    """Write the triage folder for the experiment named in the config; returns it."""
    experiment = experiment or load_experiment(config.experiment_config)
    tables_dir = config.tables_root / experiment.run_id
    provenance = verified_provenance(experiment, tables_dir)
    explain_dir = tables_dir / "explainability"
    sources = {
        "comparisons": tables_dir / "comparisons.csv",
        "oof_predictions": tables_dir / "oof_predictions.csv",
        "importance_per_task": explain_dir / "importance_per_task.csv",
        "coefficient_signs": explain_dir / "coefficient_signs.csv",
        "gene_set_tests": explain_dir / "gene_set_tests.csv",
        "score_correlation": explain_dir / "gene_set_score_correlation.csv",
    }
    if config.external_evidence is not None:
        sources["external_evidence"] = config.external_evidence
    missing = [str(p) for p in sources.values() if not p.is_file()]
    if missing:
        raise tr.TriageError(f"missing inputs: {missing}")

    gate, verdict = gate_status(pd.read_csv(sources["comparisons"]))
    evidence = tr.pathway_evidence(
        pd.read_csv(sources["importance_per_task"], index_col=0),
        pd.read_csv(sources["coefficient_signs"], index_col=0),
        pd.read_csv(sources["gene_set_tests"], index_col=0),
        pd.read_csv(sources["score_correlation"], index_col=0),
    )
    external = (
        pd.read_csv(config.external_evidence, dtype=str) if config.external_evidence else None
    )
    required_fits = experiment.k_outer * experiment.repeats
    pathways = tr.attach_external_evidence(
        tr.rank_pathways(evidence, config.pathway, gate, required_fits), external
    )
    oof = pd.read_csv(sources["oof_predictions"])
    lines = tr.cell_line_evidence(oof, cell_line_metadata(experiment))
    discrepancies = tr.rank_discrepancies(lines, config.cell_lines, gate)
    priorities = tr.replication_priorities(discrepancies)

    manifest = {
        **provenance,
        "triage_config_sha256": config.sha256,
        "triage_config": dict(config.raw),
        "code_sha256": code_sha256(),
        "source_sha256": {name: file_sha256(path) for name, path in sources.items()},
        "primary_verdict": verdict,
        "primary_gain_shown": gate,
        "primary_status": "primary gain shown" if gate else "primary gain not shown",
        "required_real_fits": required_fits,
        "rules": {"pathway": asdict(config.pathway), "cell_lines": asdict(config.cell_lines)},
        "criteria_text": tr.criteria_text(config.pathway, config.cell_lines),
        "tiers": list(tr.TIERS),
        "tier_counts": {
            name: {str(k): int(v) for k, v in table["tier"].value_counts().items()}
            for name, table in (
                ("pathway_candidates", pathways),
                ("discrepancy_review", discrepancies),
                ("cell_line_validation_priorities", priorities),
            )
        },
        "deferred": DEFERRED,
        "limitations": LIMITATIONS,
        "statement": tr.STATEMENT,
    }

    def build(staging: Path) -> None:
        pathways.to_csv(staging / "pathway_candidates.csv", index=False)
        priorities.to_csv(staging / "cell_line_validation_priorities.csv", index=False)
        discrepancies.to_csv(staging / "discrepancy_review.csv", index=False)
        write_json(staging / "triage_manifest.json", manifest)

    out = config.output_dir / experiment.run_id
    write_once_folder(out, build)
    return out
